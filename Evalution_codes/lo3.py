LUMA_ON = 70   # pixels darker than this (the black outline / bevel lines) stay empty

def _enable_windows_ansi():
    if os.name != "nt":
        return
    try:
        import ctypes
        k = ctypes.windll.kernel32
        h = k.GetStdHandle(-11)
        m = ctypes.c_ulong()
        k.GetConsoleMode(h, ctypes.byref(m))
        k.SetConsoleMode(h, m.value | 0x0004)
    except Exception:
        os.system("")

def _q256(r, g, b):
    if abs(r - g) < 12 and abs(g - b) < 12:
        v = (r + g + b) // 3
        return 16 if v < 8 else 231 if v > 248 else 232 + (v - 8) * 24 // 240
    c = lambda x: min(5, (x * 6) // 256)
    return 16 + 36 * c(r) + 6 * c(g) + c(b)

_BITS = ((0x01, 0x08), (0x02, 0x10), (0x04, 0x20), (0x40, 0x80))  # [row][col]

def render(size="auto", mode="braille", color=None):
    if color is None:
        color = sys.stdout.isatty() and "NO_COLOR" not in os.environ
    cols = shutil.get_terminal_size((80, 24)).columns
    names = {"small": 0, "medium": 1, "large": 2}
    if size in names:
        idx = names[size]
    else:
        idx = 0
        for i, t in enumerate(TIERS):
            if t[0] // 2 + 4 <= cols:
                idx = i
    w, h, data = TIERS[idx]
    px = zlib.decompress(base64.b64decode("".join(data.split())))
    q = bool(os.environ.get("IQ_256")) or os.environ.get("TERM") in ("linux", "dumb")
    fg = (lambda c: "38;5;%d" % _q256(*c)) if q else (lambda c: "38;2;%d;%d;%d" % c)
    bg = (lambda c: "48;5;%d" % _q256(*c)) if q else (lambda c: "48;2;%d;%d;%d" % c)
    def at(x, y):
        i = (y * w + x) * 4
        return px[i], px[i + 1], px[i + 2], px[i + 3]
    out = []
    if mode == "braille":
        for cy in range(0, h, 4):
            line, last = "", None
            for cx in range(0, w, 2):
                bits, sr, sg, sb, n = 0, 0, 0, 0, 0
                for dy in range(4):
                    for dx in range(2):
                        r, g, b, a = at(cx + dx, cy + dy)
                        if a > 128 and (r * 3 + g * 6 + b) // 10 > LUMA_ON:
                            bits |= _BITS[dy][dx]; sr += r; sg += g; sb += b; n += 1
                if not bits:
                    line += " "; last = None if last else last
                    continue
                ch = chr(0x2800 + bits)
                if color:
                    c = (sr // n, sg // n, sb // n)
                    line += "\033[%sm%s" % (fg(c), ch)
                else:
                    line += ch
            out.append("  " + line + ("\033[0m" if color else ""))
    else:  # half-block, 2x2 averaged
        def avg(cx, cy):
            s = [0, 0, 0, 0]
            for dy in range(2):
                for dx in range(2):
                    p = at(cx + dx, cy + dy)
                    for k in range(4): s[k] += p[k]
            return tuple(v // 4 for v in s)
        for cy in range(0, h - 1, 4):
            line = ""
            for cx in range(0, w, 2):
                t, b = avg(cx, cy), avg(cx, cy + 2)
                to, bo = t[3] > 100, b[3] > 100
                if not color:
                    line += "█" if to and bo else "▀" if to else "▄" if bo else " "
                elif to and bo: line += "\033[%s;%sm▀" % (fg(t[:3]), bg(b[:3]))
                elif to:        line += "\033[0;%sm▀" % fg(t[:3])
                elif bo:        line += "\033[0;%sm▄" % fg(b[:3])
                else:           line += "\033[0m "
            out.append("  " + line + ("\033[0m" if color else ""))
    return "\n".join(out)

def show_logo(size="auto", mode="braille"):
    _enable_windows_ansi()
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    print("\n" + render(size, mode) + "\n")

if __name__ == "__main__":
    args = sys.argv[1:]
    mode = "block" if "block" in args else "braille"
    size = next((a for a in args if a in ("small", "medium", "large")), "auto")
    show_logo(size, mode)
